// Writes src/stories/start-here/screen-index-data.ts: every story under Prototypes/,
// grouped by prototype and area, in the sidebar's order. Prototypes › Screen index renders it.
//
//   npm run storybook                       (in another terminal; serves :6017)
//   node scripts/build-screen-index.mjs     (reads http://localhost:6017/index.json)
//   node scripts/build-screen-index.mjs path/to/index.json
//
// MDX can't read Storybook's index at build time, so the list is generated here and
// checked in. Re-run it after adding, renaming or moving a prototype story.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "src/stories/start-here/screen-index-data.ts");
const arg = process.argv[2];
const index = arg ? JSON.parse(readFileSync(arg, "utf8")) : await (await fetch(`${process.env.STORYBOOK_URL ?? "http://localhost:6017/"}index.json`)).json();

/** Prototype folders, and the area order inside each, as the sidebar sorts them (.storybook/preview.tsx). */
const ORDER = {
    "MCG Prototype 3": ["Instruction", "Programs"],
    "MCG Prototype 1": [
        "Home",
        "Tee Times",
        "Shop",
        "Events & Clinics",
        "Academy",
        "Instructor Profile",
        "Lesson Booking",
        "Lesson Review",
        "Grill",
        "Account",
    ],
    Instruction: ["Book a Lesson", "Packages & Credits", "Elements", "*Model Comparison*"],
    "Golfer web · Sagamore & clubs": [
        "Global Nav › Tee Times",
        "Global Nav › Pro Shop",
        "Global Nav › Events",
        "Global Nav › Calendar",
        "Global Nav › Clinics",
        "Global Nav › Restaurant",
        "Tee Time Checkout",
        "Shop Checkout",
        "Profile ∕ Account",
    ],
};

const tidy = (s) => s.replace(/^\*(.*)\*$/, "$1");

const groups = new Map(Object.keys(ORDER).map((p) => [p, new Map(ORDER[p].map((a) => [a, []]))]));
const unplaced = [];

for (const entry of Object.values(index.entries)) {
    if (entry.type !== "story") continue;
    const parts = entry.title.split("/");
    if (parts[0] !== "Prototypes" || !groups.has(parts[1])) continue;
    const prototype = parts[1];
    const rest = parts.slice(2);
    // Global Nav is big, so it splits one level deeper (Global Nav › Tee Times, › Pro Shop, …).
    const depth = rest[0] === "Global Nav" ? 2 : 1;
    const area = rest.slice(0, depth).join(" › ");
    // The label is the rest of the title plus the story name, without saying a word twice:
    // "Shop Checkout/1. Cart" + "Cart" is "1. Cart"; "Pro Shop/Product" + "Product — Sold Out"
    // is "Product — Sold Out".
    const page = rest.slice(depth).map(tidy);
    const name = tidy(entry.name);
    const last = page[page.length - 1];
    let label;
    if (!last) label = name;
    else if (name.startsWith(last)) label = [...page.slice(0, -1), name].join(" · ");
    else if (last.endsWith(name)) label = page.join(" · ");
    else label = [...page, name].join(" · ");
    const areas = groups.get(prototype);
    if (!areas.has(area)) {
        unplaced.push(entry.id);
        areas.set(area, []);
    }
    areas.get(area).push([label, entry.id]);
}

const data = [...groups].map(([prototype, areas]) => ({
    prototype,
    areas: [...areas].filter(([, screens]) => screens.length).map(([area, screens]) => ({ area: tidy(area), screens })),
}));

const total = data.reduce((n, p) => n + p.areas.reduce((m, a) => m + a.screens.length, 0), 0);
const body = `// Generated by scripts/build-screen-index.mjs from Storybook's index.json. Do not edit by hand.
// ${total} prototype stories.

export interface IndexArea {
    area: string;
    /** [label, story id] */
    screens: [string, string][];
}

export interface IndexPrototype {
    prototype: string;
    areas: IndexArea[];
}

export const SCREEN_INDEX: IndexPrototype[] = ${JSON.stringify(data, null, 4)};
`;
writeFileSync(out, body);
// Format it the way the rest of the repo is formatted (.prettierrc).
execFileSync("npx", ["prettier", "--write", out], { cwd: root, stdio: "ignore" });
console.log(`Wrote ${path.relative(root, out)}: ${total} stories in ${data.length} prototypes.`);
if (unplaced.length) console.log(`Areas not in ORDER (added last): ${unplaced.join(", ")}`);
